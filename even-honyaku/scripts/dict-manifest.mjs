// Regenerates src/dictionary-manifest.ts: the name, size and SHA-256 of every kuromoji dictionary file, read from the
// installed package. The app downloads these files on demand (Google Translate users only) from a CDN pinned to this exact
// package version and refuses any file that doesn't match, so the list must come from the package itself.
// Run: npm run dict:manifest   (and again whenever the kuromoji version changes; a test fails if it is stale)
import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkgDir = join(root, 'node_modules', 'kuromoji')
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version
const files = readdirSync(join(pkgDir, 'dict'))
  .filter((f) => f.endsWith('.dat.gz'))
  .sort()
  .map((name) => {
    const data = readFileSync(join(pkgDir, 'dict', name))
    return { name, bytes: data.length, sha256: createHash('sha256').update(data).digest('hex') }
  })

const out = `// GENERATED by scripts/dict-manifest.mjs from node_modules/kuromoji. Do not edit by hand.
import type { DictFile } from './core/dictionary'

export const DICT_PACKAGE = 'kuromoji'
export const DICT_VERSION = '${version}'
export const DICT_FILES: DictFile[] = [
${files.map((f) => `  { name: '${f.name}', bytes: ${f.bytes}, sha256: '${f.sha256}' },`).join('\n')}
]
`
writeFileSync(join(root, 'src', 'dictionary-manifest.ts'), out)
console.log(`wrote src/dictionary-manifest.ts: kuromoji@${version}, ${files.length} files, ${(files.reduce((n, f) => n + f.bytes, 0) / 1e6).toFixed(1)} MB`)
